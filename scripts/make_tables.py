# A sign before a digit becomes a math minus; en dashes in ranges ("0.1--0.2") are left alone.
MINUS = re.compile(r"(?<![-\w])-(?=\d)")


def f3(x):
    return f"{x:.3f}"


def pct(x, d=1):
    return f"{100 * x:.{d}f}\\%"


def sel(df, scenario, beta, **kw):
    m = df["scenario"] == scenario
    m &= df["beta"].isna() if beta is None else np.isclose(df["beta"].fillna(-9), beta)
    for k, v in kw.items():
        m &= np.isclose(df[k], v) if isinstance(v, float) else (df[k] == v)
    return df[m]


def metric(summ, scenario, beta, method, cc, name, alpha=0.1):
    d = sel(summ, scenario, beta, method=method, cc=cc, metric=name, alpha=alpha)
    return d.set_index("predictor")["mean"].reindex(PRED)


class Macros:
    def __init__(self):
        self.items = []

    def __setitem__(self, name, value):
        assert name.isalpha(), name
        self.items.append((name, value))

    def write(self, path):
        lines = ["% Generated by scripts/make_tables.py from results/; do not edit."]
        lines += [f"\\newcommand{{\\{n}}}{{{MINUS.sub('$-$', str(v))}}}" for n, v in self.items]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def rng(values):
    v = np.asarray(values, float)
    return f"{v.min():.3f}--{v.max():.3f}"


