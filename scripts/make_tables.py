        M[f"{tag}DiffGwcpNpos"] = f"{int((vs_g['ci_lo'] > 0).sum())}"
        M[f"{tag}DiffHcpEsm"] = f"{vs_h.loc['ESM1b', 'diff']:+.3f} [{vs_h.loc['ESM1b', 'ci_lo']:+.3f}, {vs_h.loc['ESM1b', 'ci_hi']:+.3f}]"
