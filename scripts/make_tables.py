def sens_macros(M, sens):
    """Pathogenic coverage of class-conditional HCP and ProtCOVER under the alternative family definitions."""
    cells = [("S2", 1.0), ("S2", 2.0), ("S3", None), ("S4", None)]
    means, mins = [], {}
    for tag, nm in [("sens_mm050", "Fifty"), ("sens_hc", "Hc")]:
        df = sens.get(tag)
        if df is None:
            continue
        for m, mt in [("P_w", "Pw"), ("B3_pool", "Hcp")]:
            vals = [sel(df, sc, b, method=m, cc=True, alpha=0.1).set_index("predictor")["cov_path_family_mean"].reindex(PRED)
                    for sc, b in cells]
            if m == "P_w":
                means += [v.mean() for v in vals]
            mins[(nm, mt)] = min(v.min() for v in vals)
    if means:
        M["sensPwMeanRange"] = rng(means)
        for (nm, mt), v in mins.items():
            M[f"sens{nm}{mt}Min"] = f3(v)


def shortfall_macros(M, seed_summ):
    """Shortfall of the worse class below the target over the shifted cells (S2 beta > 0, S3 and S4,
    five predictors), class-conditional methods at alpha = 0.1; seed variability; set-size cost."""
    s = seed_summ[np.isclose(seed_summ["alpha"], 0.1) & (seed_summ["cc"] == True)]
    s = s[is_shifted(s)]
    names = {**FAMILY, "P_w[variant]": "VarW", "P_full": "Full"}
    for m, nm in names.items():
        short, worst = shortfall(seed_summ, m)
        d = s[s["method"] == m]
        M[f"short{nm}Mean"], M[f"short{nm}Max"] = f3(short.mean()), f3(short.max())
        M[f"short{nm}N"] = f"{int((worst < 0.89).sum())}"
        M[f"worst{nm}"] = f3(worst.min())
        w = worst.min()  # four decimals only where three would round up onto 0.890 or 0.900
        M[f"worst{nm}Fine"] = f"{w:.4f}" if any(w < b <= round(w, 3) for b in (0.89, 0.9)) else f3(w)
        M[f"meanWorst{nm}"] = f3(worst.mean())
        M[f"sOneMeanWorst{nm}"] = f3(shortfall(seed_summ, m, [("S1", 0.0)])[1].mean())
        M[f"size{nm}Shift"] = f"{d['set_size_mean'].mean():.2f}"
        M[f"full{nm}Shift"] = pct(d["full_set_rate_mean"].mean(), 0)
        M[f"under{nm}Shift"] = pct(d["frac_fam_below_mean"].mean(), 0)
        M[f"singErr{nm}Shift"] = f3(d["ret_singleton_error_mean"].mean())
        # The shifts that the descriptors were not chosen for: S3 and S4.
        for cells, tag in [([("S2", 0.5), ("S2", 1.0), ("S2", 2.0)], "Two"), ([("S3", None)], "Three"), ([("S4", None)], "Four"),
                           ([("S3", None), ("S4", None)], "Ind")]:
            sh, wo = shortfall(seed_summ, m, cells)
            M[f"short{nm}{tag}Mean"], M[f"short{nm}{tag}Max"] = f3(sh.mean()), f3(sh.max())
            M[f"worst{nm}{tag}"] = f3(wo.min())
        if m in FAMILY:
            for a, tag in [(0.05, "Five"), (0.2, "Twenty")]:
                sh, wo = shortfall(seed_summ, m, alpha=a)
                M[f"short{nm}Mean{tag}"], M[f"short{nm}N{tag}"] = f3(sh.mean()), f"{int((wo < 1 - a - 0.01).sum())}"
    # Per-cell comparison with the pre-registered margin: shortfall differences below 0.01 count as none.
    for cells, tag in [(SHIFTED, ""), ([("S2", 0.5), ("S2", 1.0), ("S2", 2.0)], "Two"), ([("S3", None), ("S4", None)], "Ind")]:
        cr = shortfall(seed_summ, "C_ratio", cells)[0]
        M[f"nShiftCells{tag}"] = f"{len(cr)}"
        for m, nm in [("B3_pool", "Hcp"), ("B4_gwcp", "Gwcp"), ("P_w", "Pw"), ("C_supp", "Cs")]:
            d = shortfall(seed_summ, m, cells)[0].reindex(cr.index) - cr
            M[f"marginCr{nm}Better{tag}"] = f"{int((d > 0.01).sum())}"
            M[f"marginCr{nm}Worse{tag}"] = f"{int((d < -0.01).sum())}"
    M["underNullShift"] = pct(s[s["method"] == "P_w"]["null_frac_fam_below_mean"].mean(), 0)
    for m, nm in [("P_w", "Pw"), ("C_ratio", "Cr")]:
        d = s[s["method"] == m]
        M[f"seedSd{nm}Path"] = f"{d['cov_path_family_std'].min():.3f}--{d['cov_path_family_std'].max():.3f}"
        M[f"full{nm}Range"] = f"{100 * d['full_set_rate_mean'].min():.0f}--{100 * d['full_set_rate_mean'].max():.0f}\\%"
    cr = s[s["method"] == "C_ratio"]
    M["condAbstainMax"] = pct(cr["abstain_rate_family_mean"].max(), 2)
    s5 = seed_summ[np.isclose(seed_summ["alpha"], 0.05) & (seed_summ["cc"] == True) & (seed_summ["method"] == "C_ratio")]
    M["condAbstainMaxFive"] = pct(s5[is_shifted(s5)]["abstain_rate_family_mean"].max(), 1)
    # Sensitivity to the margin: cells where ProtCOVER's shortfall is smaller (larger) than GWCP's and HCP's
    # by more than half or twice the pre-registered 0.01.
    crs = shortfall(seed_summ, "C_ratio")[0]
    for m, nm in [("B4_gwcp", "Gwcp"), ("B3_pool", "Hcp")]:
        d = shortfall(seed_summ, m)[0].reindex(crs.index) - crs
        for mg, mn in [(0.005, "Half"), (0.02, "Double")]:
            M[f"marginCr{nm}Better{mn}"], M[f"marginCr{nm}Worse{mn}"] = f"{int((d > mg).sum())}", f"{int((d < -mg).sum())}"


def realistic_macros(M, sens):
    """Robustness runs of the base model and descriptors: the transductive run (base model also on the
    score standardized within its protein, variant-count descriptor; prefix std) and the alignment-free
    run (no alignment-depth descriptor; prefix noMsa)."""
    for tag, pre in [("standardized", "std"), ("nomsa", "noMsa")]:
        df = sens.get(tag)
        if df is None:
            continue
        s = df[np.isclose(df["alpha"], 0.1) & (df["cc"] == True)]
        b2 = s[(s["scenario"] == "S1") & (s["method"] == "B1_split")].set_index("predictor").reindex(PRED)
        M[f"{pre}BtwoPath"] = rng(b2["cov_path_family_mean"])  # all five predictors
        M[f"{pre}BtwoNBelow"] = f"{int((b2['cov_path_family_mean'] < 0.9).sum())}"
        worse = b2[["cov_path_family_mean", "cov_benign_family_mean"]].min(axis=1)
        M[f"{pre}BtwoWorst"], M[f"{pre}BtwoWorstNBelow"] = rng(worse), f"{int((worse < 0.9).sum())}"
        benign = b2.index[(b2["cov_benign_family_mean"] < b2["cov_path_family_mean"]) & (worse < 0.9)]
        M[f"{pre}BtwoBenignWorse"] = ", ".join(PRED_TEX[p] for p in benign) or "none"
        s = s[is_shifted(s)]
        for m, nm in FAMILY.items():
            if not (s["method"] == m).any():
                continue
            short, worst = shortfall(df, m)
            M[f"{pre}Short{nm}Mean"], M[f"{pre}Worst{nm}"] = f3(short.mean()), f3(worst.min())
            M[f"{pre}Size{nm}"] = f"{s[s['method'] == m]['set_size_mean'].mean():.2f}"
            for cells, ct in [([("S2", 0.5), ("S2", 1.0), ("S2", 2.0)], "Two"), ([("S3", None), ("S4", None)], "Ind")]:
                M[f"{pre}Short{nm}{ct}Mean"] = f3(shortfall(df, m, cells)[0].mean())
        cr = shortfall(df, "C_ratio")[0]
        for m, nm in [("B3_pool", "Hcp"), ("B4_gwcp", "Gwcp")]:
            d = shortfall(df, m)[0].reindex(cr.index) - cr
            M[f"{pre}MarginCr{nm}Better"], M[f"{pre}MarginCr{nm}Worse"] = f"{int((d > 0.01).sum())}", f"{int((d < -0.01).sum())}"


def margin_macros(M, summ):
    """Noise levels that put the 0.01 margin in context: over the shifted cells, family-level
    class-conditional methods at alpha 0.1, the median half-width of a cell's 95% bootstrap interval
    and the median seed-to-seed s.d. of class-wise coverage."""
    s = summ[np.isclose(summ["alpha"], 0.1) & (summ["cc"] == True) & summ["method"].isin(list(FAMILY))
             & summ["metric"].isin(["cov_path_family", "cov_benign_family"])]
    s = s[is_shifted(s)]
    M["marginBootHw"] = f3(((s["ci_hi"] - s["ci_lo"]) / 2).median())
    M["marginSeedSd"] = f3(s["sd_seeds"].median())


