    M["sOneBtwoPathTrancept"] = f3(b2["TranceptEVE_L"])
    M["sOneBtwoPathVar"] = rng(metric(summ, "S1", 0.0, "B1_split", True, "cov_path_variant")[nt])
    M["sOneBoneCovFam"] = rng(metric(summ, "S1", 0.0, "B1_split", False, "cov_family"))
